<?php

/*
|--------------------------------------------------------------------------
| Database Configuration
|--------------------------------------------------------------------------
*/

$host = "localhost";
$username = "root";
$password = "";
$database = "digital_suggestion_box";


/*
|--------------------------------------------------------------------------
| Create Database Connection
|--------------------------------------------------------------------------
*/

$conn = new mysqli(
    $host,
    $username,
    $password,
    $database
);


/*
|--------------------------------------------------------------------------
| Check Connection
|--------------------------------------------------------------------------
*/

if ($conn->connect_error) {
    die("Database connection failed.");
}


/*
|--------------------------------------------------------------------------
| Set UTF-8 Character Set
|--------------------------------------------------------------------------
*/

$conn->set_charset("utf8mb4");

?>